import { promises as fs } from "node:fs";
import path from "node:path";

import {
  ALLOWED_CATEGORIES,
  ALLOWED_DIFFICULTIES,
  ALLOWED_TASK_TYPES,
  ROOT,
  readTopicCatalog,
} from "./lib/task-data.mjs";

const TASK_INDEX_FILE = path.join(ROOT, "data", "task-index.json");
const LEARNING_SUMMARY_FILE = path.join(
  ROOT,
  "data",
  "learning-summary.json",
);
const OUTPUT_FILE = path.join(
  ROOT,
  "chatgpt",
  "task-designer-context.md",
);

async function readJson(filePath) {
  return JSON.parse(await fs.readFile(filePath, "utf8"));
}

function listOrNone(items, formatter) {
  if (items.length === 0) {
    return ["- none"];
  }

  return items.map(formatter);
}

function buildContext(taskIndex, learningSummary, catalog) {
  const revisitLines = listOrNone(
    learningSummary.topicsToRevisit.slice(0, 10),
    (topic) =>
      `- ${topic.topicId} (${topic.priority}): ${topic.evidenceCount} unresolved signal(s), ${topic.coachHints} coach event(s), tasks: ${topic.relatedTasks.join(", ")}`,
  );
  const underPracticedLines = listOrNone(
    learningSummary.underPracticedTopics.slice(0, 12),
    (topic) => `- ${topic.topicId} — ${topic.label} (${topic.category})`,
  );
  const recentTaskLines = listOrNone(
    learningSummary.recentTasks.slice(0, 12),
    (task) =>
      `- ${task.slug}: ${task.category} / ${task.taskType} / ${task.difficulty}; shape=${task.problemShape}; status=${task.status}; mastery=${task.mastery ?? "-"}`,
  );
  const catalogLines = catalog.topics.map(
    (topic) => `- ${topic.id} — ${topic.label} (${topic.category})`,
  );
  const categoryCoverage = Object.entries(learningSummary.categoryCoverage)
    .map(([category, count]) => `${category}=${count}`)
    .join(", ");
  const taskTypeCoverage = Object.entries(learningSummary.taskTypeCoverage)
    .map(([taskType, count]) => `${taskType}=${count}`)
    .join(", ");

  return [
    "# ChatGPT Task Designer Context",
    "",
    "> Generated from repository contracts and learning data.",
    "> Do not edit this file manually. Attach it to ChatGPT when task brainstorming is useful.",
    "",
    "## Role",
    "",
    "Design one realistic, interview-sized live-coding task. Discuss ideas with the user when requested. When the user asks for the final artifact, output exactly one Live Coding Task Package v1 and no surrounding explanation.",
    "",
    "Codex, not ChatGPT, validates the package, creates repository files, scaffolds code, runs the interview session, and writes the review.",
    "",
    "## Selection priorities",
    "",
    "1. Prefer a high-value topic currently worth revisiting when it can be tested in a different scenario.",
    "2. Otherwise prefer an under-practiced topic and an underused category/taskType/problemShape combination.",
    "3. Respect explicit user constraints for difficulty, focus, and exclusions.",
    "4. Do not repeat the same problem shape or surface scenario too soon.",
    "5. Keep the task focused on one or two primary skills and at most three follow-ups.",
    "",
    "## Current topics to revisit",
    "",
    ...revisitLines,
    "",
    "## Under-practiced topics (bounded view)",
    "",
    ...underPracticedLines,
    "",
    "## Recent tasks",
    "",
    ...recentTaskLines,
    "",
    "## Coverage",
    "",
    `- Total tasks: ${taskIndex.tasks.length}`,
    `- Categories: ${categoryCoverage || "none"}`,
    `- Task types: ${taskTypeCoverage || "none"}`,
    "",
    "## Allowed taxonomy",
    "",
    `- Categories: ${ALLOWED_CATEGORIES.join(", ")}`,
    `- Task types: ${ALLOWED_TASK_TYPES.join(", ")}`,
    `- Difficulties: ${ALLOWED_DIFFICULTIES.join(", ")}`,
    "- Use category for the technical domain and taskType for the candidate activity.",
    "- Do not use debugging or refactor as categories.",
    "",
    "## Canonical topics",
    "",
    ...catalogLines,
    "",
    "## Required Task Package v1 output",
    "",
    "````markdown",
    "---",
    "schemaVersion: 1",
    'slug: "lowercase-kebab-case"',
    "---",
    "",
    "# Live Coding Task Package",
    "",
    "## task.md",
    "",
    "```markdown",
    "---",
    'title: "..."',
    'category: "..."',
    'taskType: "..."',
    'difficulty: "..."',
    'primarySkill: "..."',
    'secondarySkill: "..."',
    'problemShape: "..."',
    'interviewFocus: "..."',
    "reviewFocus:",
    '  - "correctness"',
    "tags:",
    '  - "..."',
    "---",
    "",
    "# Task title",
    "",
    "## Context",
    "...",
    "",
    "## Goal",
    "...",
    "",
    "## Requirements",
    "...",
    "",
    "## Acceptance Criteria",
    "...",
    "```",
    "",
    "## interviewer.md",
    "",
    "```markdown",
    "---",
    "schemaVersion: 1",
    "plannedFollowUps: 1",
    "primaryTopics:",
    '  - "canonical-topic-id"',
    "secondaryTopics:",
    '  - "canonical-topic-id"',
    "---",
    "",
    "# Interviewer Plan",
    "",
    "## Core Task",
    "",
    "### Purpose",
    "...",
    "",
    "### Expected evidence",
    "- ...",
    "",
    "### Checkpoint focus",
    "- ...",
    "",
    "### Review focus",
    "- ...",
    "",
    "## Follow-up 1",
    "",
    "### Reveal",
    "...",
    "",
    "### Purpose",
    "...",
    "",
    "### Topics",
    "- canonical-topic-id",
    "",
    "### Expected evidence",
    "- ...",
    "",
    "### Review focus",
    "- ...",
    "```",
    "````",
    "",
    "## Content rules",
    "",
    "- The candidate brief must be self-contained and must not reveal follow-ups, hidden edge cases, solution structure, code, pseudocode, or hints.",
    "- The interviewer plan may describe expected evidence and concepts, but must not contain a complete solution.",
    "- Use zero to three follow-ups. Each follow-up must add meaningful learning value.",
    "- Use only canonical topic IDs listed above.",
    "- Include hasPreview and previewEntry in task.md only for a visible UI task.",
    "- Do not output scaffold code; Codex creates it after import.",
    "",
  ].join("\n");
}

async function main() {
  const [taskIndex, learningSummary, catalog] = await Promise.all([
    readJson(TASK_INDEX_FILE),
    readJson(LEARNING_SUMMARY_FILE),
    readTopicCatalog(),
  ]);
  const content = buildContext(taskIndex, learningSummary, catalog);

  await fs.mkdir(path.dirname(OUTPUT_FILE), { recursive: true });
  await fs.writeFile(OUTPUT_FILE, content, "utf8");
  console.log("Generated chatgpt/task-designer-context.md");
}

void main();
