import { promises as fs } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { ROOT, loadRepository } from "./lib/task-data.mjs";

export async function generatePreviewManifest(records) {
  const tasks = records.filter((record) => record.metadata.hasPreview === true);
  const imports = tasks.map((task, index) => `import Preview${index} from ${JSON.stringify(`../../tasks/${task.category}/${task.slug}/${task.metadata.previewEntry.replace(/\.tsx$/, "")}`)};`);
  const cases = tasks.map((task, index) => `    case ${JSON.stringify(task.slug)}: return <Preview${index} />;`);
  const source = ["// Generated by npm run finalize:tasks. Do not edit.", ...imports, "", "export function renderTaskPreviewFromManifest(slug: string) {", "  switch (slug) {", ...cases, "    default: return null;", "  }", "}", ""].join("\n");
  await fs.mkdir(path.join(ROOT, "src/lib"), { recursive: true });
  await fs.writeFile(path.join(ROOT, "src/lib/generated-task-preview-manifest.tsx"), source);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { records } = await loadRepository();
  await generatePreviewManifest(records);
  console.log("Generated preview manifest.");
}
